// Original cooking ideas; never use these recipes as canning/fermentation processes.
// All recipe quantities are for baseServings; servings scaled via measurement only.
export const RECIPE_BY_ID = Object.fromEntries(RECIPES.map(r=>[r.id,r]));
export const SERVINGS_OPTIONS=[2,4,6,8];
export function formatQuantity(value){
  if(!Number.isFinite(value)||value<0)throw new RangeError("Quantity must be nonnegative");
  const rounded=Math.round(value*8)/8,whole=Math.floor(rounded);
  const frac=Math.round((rounded-whole)*8),parts={1:"⅛",2:"¼",3:"⅜",4:"½",5:"⅝",6:"¾",7:"⅞"};
  if(frac===0)return String(whole);
  return whole>0?String(whole)+" "+parts[frac]:parts[frac];
}
export function recipeIngredients(recipe,servings){
  if(!RECIPE_BY_ID[recipe?.id]||!SERVINGS_OPTIONS.includes(servings))throw new RangeError("Unsupported recipe/servings");
  return recipe.ingredients.map(([quantity,unit,label])=>{
    if(quantity===null)return label;
    const scaled=quantity*servings/recipe.baseServings;
    const displayUnit=scaled===1&&["cups","cloves"].includes(unit)?unit.slice(0,-1):unit;
    return [formatQuantity(scaled),displayUnit,label].filter(Boolean).join(" ");
  });
}
export function kitchenCropsCoverage(){
  return [...new Set(RECIPES.flatMap(recipe=>recipe.crops))];
}
export function validateMealPlan(entry){
  if(!entry||typeof entry!=="object")return false;
  if(typeof entry.id!=="string"||entry.id.length<1||entry.id.length>90)return false;
  if(typeof entry.recipeId!=="string"||!Object.hasOwn(RECIPE_BY_ID,entry.recipeId))return false;
  if(!SERVINGS_OPTIONS.includes(entry.servings))return false;
  if(typeof entry.date!=="string"||!/^\d{4}-\d{2}-\d{2}$/.test(entry.date))return false;
  const [y,m,d]=entry.date.split("-").map(Number),check=new Date(Date.UTC(y,m-1,d));
  if(check.getUTCFullYear()!==y||check.getUTCMonth()!==m-1||check.getUTCDate()!==d)return false;
  if(typeof entry.note!=="string"||entry.note.length>200)return false;
  return typeof entry.done==="boolean";
}
